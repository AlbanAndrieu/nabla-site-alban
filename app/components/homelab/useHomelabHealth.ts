/**
 * Revalidates the canonical catalog periodically while polling service health.
 * Refreshes pause in hidden tabs and resume on visibility changes.
 */
export function useHomelabHealth(readOnly = false): HomelabServicesState {
	const [state, setState] = useState<HomelabServicesState>(
		INITIAL_HOMELAB_SERVICES_STATE,
	);

	useEffect(() => {
		// A reauthorization can change the mode while the hook stays mounted.
		// The scope guard below hides old data during that transition.
		const initialController = new AbortController();
		let refreshController: AbortController | null = null;
		let catalogRefreshController: AbortController | null = null;
		let lastCatalogAttemptAt = 0;
		let ownerUpstreamBlocked = false;
		let lastCycleStartedAt = 0;
		let consecutiveHealthFailures = 0;
		let nextHealthAttemptAt = 0;
		// Only a publicly authorized projection may be written to persistent storage.
		const publicStorage = (() => {
			if (!readOnly) return null;
			try {
				return window.localStorage;
			} catch {
				return null;
			}
		})();
		const cachedCatalog = publicStorage ? readPublicCatalogCache(publicStorage) : null;
		let activeCatalogRevision = cachedCatalog?.catalog.catalogRevision ?? null;
		// Hydrate after effect setup rather than setting state synchronously
		// from the effect body. Abort the update if access mode has changed.
		// Only the validated SERVICE cache can enter public browser state.
		queueMicrotask(() => {
			if (initialController.signal.aborted) return;
			setState(cachedCatalog
				? {
					...INITIAL_HOMELAB_SERVICES_STATE,
					catalog: cachedCatalog.catalog,
					topology: cachedCatalog.topology,
					catalogStale: true,
					catalogScope: "public",
					// Stale health is never promoted to a fresh/green probe.
					siteHealth: publicStorage && activeCatalogRevision
						? readStalePublicHealthCache(publicStorage, activeCatalogRevision)
						: null,
					healthUnavailable: true,
				}
				: INITIAL_HOMELAB_SERVICES_STATE);
		});

		const runHealthCycle = async (signal: AbortSignal) => {
			lastCycleStartedAt = Date.now();
			// Each failed cycle increases the spacing; a healthy cycle resets it.
			const recordCycle = (successful: boolean) => {
				if (signal.aborted) return;
				consecutiveHealthFailures = successful ? 0 : consecutiveHealthFailures + 1;
				nextHealthAttemptAt = successful ? 0 : Date.now() + homelabRetryDelayMs(consecutiveHealthFailures);
			};
			setState((current) => ({ ...current, healthRefreshing: true }));
			if (readOnly) {
				// External views consume only the strict SERVICE v2 projection.
				// Do not even request private OWNER aggregate/probe endpoints.
				let siteHealth: SiteHealthV2 | null = null;
				let status: number | null = null;
				try {
					const response = await fetch("/api/homelab-health-v2", {
						cache: "no-store",
						signal: boundedHomelabSignal(signal),
						headers: { Accept: "application/json" },
					});
					status = response.status;
					if (response.ok) {
						siteHealth = parseSiteHealthV2(await response.json());
						// A new health revision cannot validate an older catalog.
						if (activeCatalogRevision && siteHealth?.catalogRevision !== activeCatalogRevision)
							siteHealth = null;
						if (siteHealth && publicStorage && activeCatalogRevision)
							writePublicHealthCache(publicStorage, siteHealth);
					}
				} catch {
					// Missing v2 evidence is UNKNOWN, not an observed outage.
				}
				if (!siteHealth && publicStorage && activeCatalogRevision) {
					// A cached green status is never a fresh measurement.
					siteHealth = readStalePublicHealthCache(
						publicStorage,
						activeCatalogRevision,
					);
				}
				if (!signal.aborted) {
					setState((current) => ({
						...current,
						siteHealth,
						snapshot: null,
						healthUnavailable: siteHealth?.boardState !== "fresh",
						healthStatus: status,
						healthRefreshing: false,
					}));
				}
				recordCycle(siteHealth?.boardState === "fresh");
				return;
			}

			// SERVICE status DTO is independent from OWNER-only probe details.
			void fetch("/api/homelab-health-v2", {
				cache: "no-store",
				signal: boundedHomelabSignal(signal),
				headers: { Accept: "application/json" },
			})
				.then(async (response) => ({
					siteHealth: response.ok ? parseSiteHealthV2(await response.json()) : null,
					traceId: /^[a-f0-9]{32}$/.test(response.headers.get("X-Nabla-Trace-ID") ?? "")
						? response.headers.get("X-Nabla-Trace-ID") : null,
					confirmed: response.headers.get("X-Nabla-Trace-Propagation") === "confirmed",
				}))
				.then(({ siteHealth, traceId, confirmed }) => {
					if (!signal.aborted)
						setState((current) => ({ ...current, siteHealth, siteHealthTraceId: traceId,
							siteHealthTraceConfirmed: Boolean(traceId && confirmed) }));
				})
				.catch(() => {
					if (!signal.aborted)
						setState((current) => ({ ...current, siteHealth: null, siteHealthTraceId: null, siteHealthTraceConfirmed: false }));
				});
			// Keep SERVICE v2 polling even after Vercel's OWNER boundary is confirmed.
			if (ownerUpstreamBlocked) {
				setState((current) => ({ ...current, healthRefreshing: false }));
				recordCycle(true);
				return;
			}
			const probesPromise = fetchProbeHealth(signal);
			const aggregatePromise = fetchHealth(signal);

			const probes = await probesPromise;
			if (signal.aborted) return;
			if (probes.snapshot) {
				setState((current) => applyProbeSnapshot(current, probes));
			}

			const aggregate = await aggregatePromise;
			if (signal.aborted) return;
			ownerUpstreamBlocked =
				aggregate.reason === "owner-boundary" &&
				probes.reason === "owner-boundary";
			setState((current) => applyHealthCycle(current, aggregate, probes));
			recordCycle(Boolean(aggregate.snapshot || probes.snapshot));
		};

		const refreshHealth = () => {
			if (document.hidden) return;
			// A tab focus right after a tick (or the initial cycle) must not
			// fire a second identical burst of health requests.
			if (Date.now() - lastCycleStartedAt < MIN_REFRESH_GAP_MS ||
				Date.now() < nextHealthAttemptAt) return;
			refreshController?.abort();
			refreshController = new AbortController();
			void runHealthCycle(refreshController.signal);
		};

		// Revalidate in long-lived tabs: a new catalogRevision would otherwise
		// leave the service graph stale while health polling continues.
		const loadCatalog = (signal: AbortSignal) => {
			lastCatalogAttemptAt = Date.now();
			void fetchCatalog(signal, readOnly)
				.then(({ catalog, topology }) => {
					if (signal.aborted) return;
					activeCatalogRevision = catalog.catalogRevision ?? null;
					if (publicStorage)
						writePublicCatalogCache(publicStorage, catalog, topology);
					setState((current) => ({
						...current,
						catalog,
						topology,
						// Never retain the previous revision's public health.
						siteHealth:
							current.siteHealth?.catalogRevision === catalog.catalogRevision
								? current.siteHealth
								: null,
						catalogFailure: null,
						catalogIncident: null,
						catalogStale: false,
						catalogScope: readOnly ? "public" : "owner",
						error: false,
					}));
				})
				.catch((error: unknown) => {
					if (signal.aborted) return;
					// 401/403/404 and explicit key denials are not transient outages.
					const revoke =
						readOnly && error instanceof CatalogV2Unavailable &&
						error.revokePublicCache;
					if (revoke) {
						activeCatalogRevision = null;
						if (publicStorage) clearPublicHomelabBrowserCache(publicStorage);
					}
					setState((current) => {
						// No stale OWNER inventory or probe may cross to SERVICE
						// during a failed revalidation. Only same-scope LKG survives.
						const { state: safe, retained: retain } =
							reconcileCatalogFailure(current, readOnly, revoke);
						return {
							...safe,
							// A 502 may reuse same-scope last-known data; revocation never may.
							error: !retain,
							catalogStale: readOnly && retain,
							catalogScope: readOnly ? "public" : "owner",
							catalogIncident: !readOnly && error instanceof CatalogV2Unavailable ? error.incident : null,
						catalogFailure:
								error instanceof CatalogV2Unavailable
									? error.reason
									: "unavailable",
						};
					});
				});
		};

		const refreshCatalogIfDue = () => {
			if (document.hidden || !catalogRevalidationDue(lastCatalogAttemptAt))
				return;
			catalogRefreshController?.abort();
			catalogRefreshController = new AbortController();
			loadCatalog(catalogRefreshController.signal);
		};

		loadCatalog(initialController.signal);

		void runHealthCycle(initialController.signal);

		const interval = window.setInterval(refreshHealth, HEALTH_REFRESH_MS);
		const catalogInterval = window.setInterval(refreshCatalogIfDue, CATALOG_REVALIDATION_MS);
		const onVisibilityChange = () => {
			if (!document.hidden) {
				refreshHealth();
				refreshCatalogIfDue();
			}
		};
		document.addEventListener("visibilitychange", onVisibilityChange);
		return () => {
			initialController.abort();
			refreshController?.abort();
			catalogRefreshController?.abort();
			window.clearInterval(interval);
			window.clearInterval(catalogInterval);
			document.removeEventListener("visibilitychange", onVisibilityChange);
		};
	}, [readOnly]);

	// Effects clean up after render. Reject the previous mode's entire
	// catalog, topology and health synchronously during an OWNER/public switch.
	if (!catalogScopeMatches(state.catalogScope, readOnly)) {
		return {
			...INITIAL_HOMELAB_SERVICES_STATE,
			error: state.error,
			healthRefreshing: state.healthRefreshing,
		};
	}
	if (readOnly) {
		return {
			...state,
			snapshot: null,
			catalogIncident: null,
			siteHealthTraceId: null,
			siteHealthTraceConfirmed: false,
			ownerBoundary: false,
			healthStatus: null,
			healthUnavailable: state.siteHealth?.boardState !== "fresh",
		};
	}
	return state;
}
